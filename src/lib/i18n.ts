export function t(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let text = DICTS[locale]?.[key] ?? DICTS.zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
