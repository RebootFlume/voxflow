/// 中文回退 G2P：逐字查拼音表 → 拼音查 IPA 表 → 输出 IPA token 序列
#[derive(Debug, Default)]
pub struct PinyinPhonemizer;

impl Phonemizer for PinyinPhonemizer {
    fn name(&self) -> &str {
        "pinyin"
    }

    fn can_handle(&self, text: &str) -> bool {
        text.chars().any(|c| matches!(c, '\u{4e00}'..='\u{9fff}'))
    }

    fn phonemize(&self, text: &str) -> Vec<String> {
        let mut out: Vec<String> = Vec::new();
        for ch in text.chars() {
            if let Some(py) = hanzi_to_pinyin(ch) {
                if let Some(ipa) = pinyin_to_ipa(py) {
                    out.extend(ipa.iter().map(|s| s.to_string()));
                }
            }
        }
        out
    }
}

