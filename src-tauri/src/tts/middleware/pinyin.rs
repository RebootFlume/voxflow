//! 中文回退 G2P：汉字 → 拼音 → IPA 音素
//!
//! espeak-ng 不可用时的中文回退路径（标准路径见 espeak.rs）。
//! - 汉字 → 拼音：内嵌 HANZI_TO_PINYIN（3799 常用汉字，来源 Unihan kHanyuPinlu）
//! - 拼音 → IPA：内嵌 PINYIN_TO_IPA（430 个标准普通话/儿化音节）
//! 所有 IPA 符号均取自 Kokoro-82M 音素表（tokenizer.json normalizer 白名单），
//! 保证 to_token_ids 能完整映射、不产生空音素。
//!
//! 说明：本回退为无调拼音 → 宽式 IPA（如 zhong → ʈʂʊŋ），
//! 不含声调箭头；精确带调 IPA 由 espeak-ng 标准路径负责（Phase 6）。

