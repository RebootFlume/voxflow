    fn test_pinyin_to_ipa_covers_common() {
        for py in ["ni", "hao", "shi", "jie", "zhong", "guo", "de", "yi", "nv", "lv", "yu", "jue"] {
            assert!(pinyin_to_ipa(py).is_some(), "missing IPA for {py}");
        }
    }

    #[test]
    fn test_phonemize_chinese_nonempty() {
        let g = PinyinPhonemizer;
        assert!(g.can_handle("你好世界"));
        let phones = g.phonemize("你好世界");
        assert!(!phones.is_empty(), "你好世界 should produce phonemes");
        // 你好世界 = ni hao shi jie → n,i,h,a,ʊ,ʂ,ɻ,t,ɕ,i,ɛ,t,ɕ,i,ɛ (15 tokens)
        assert_eq!(phones.len(), 11);
    }

