/// 查询汉字拼音（二分查找）
fn hanzi_to_pinyin(c: char) -> Option<&'static str> {
    HANZI_TO_PINYIN
        .binary_search_by_key(&c, |e| e.0)
        .ok()
        .map(|i| HANZI_TO_PINYIN[i].1)
}

/// 查询拼音 → IPA（二分查找）
fn pinyin_to_ipa(py: &str) -> Option<&'static [&'static str]> {
    PINYIN_TO_IPA
        .binary_search_by_key(&py, |e| e.0)
        .ok()
        .map(|i| PINYIN_TO_IPA[i].1)
}

